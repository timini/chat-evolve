import { useTheme, themeVars } from "../theme";
import { PROVIDERS, PROVIDER_ORDER } from "../content";
import type { Provider, ProviderId, Session, ValidationResult } from "../types";
import { BrandMark } from "../atoms/BrandMark";
import { Eyebrow } from "../atoms/Eyebrow";
import { ProviderGrid } from "../organisms/ProviderGrid";

export interface SetupPageProps {
  keys: Partial<Record<ProviderId, string>>;
  preferredModels: Partial<Record<ProviderId, string>>;
  session: Session;
  onSetKey: (provider: ProviderId, key: string) => void;
  onSetModel: (provider: ProviderId, model: string) => void;
  onBegin: () => void;
  onVerify?: (provider: Provider, key: string) => Promise<ValidationResult>;
  variantLabel?: string;
}

const RULES = [
  <>
    Keys live in <code className="ce-mono">localStorage</code>. They never leave this browser.
  </>,
  <>Every "Breed" call hits the active session's provider directly. Three variants = three parallel calls.</>,
  <>You can configure all four providers and switch between them per generation.</>,
];

/** The BYO-key gate — shown until at least one provider key is configured. */
export function SetupPage({
  keys,
  preferredModels,
  session,
  onSetKey,
  onSetModel,
  onBegin,
  onVerify,
  variantLabel = "HELIX",
}: SetupPageProps) {
  const t = useTheme();
  const configured = PROVIDER_ORDER.filter((p) => !!keys[p]);
  const hasAnyKey = configured.length > 0;
  const sessionLabel =
    hasAnyKey && session.provider
      ? `${PROVIDERS[session.provider].name.toUpperCase()} · ${session.model}`
      : "NO KEY · CANNOT GENERATE";

  return (
    <div
      className="ce"
      style={{
        ...themeVars(t),
        background: t.paper,
        color: t.ink,
        width: "100%",
        height: "100%",
        display: "grid",
        gridTemplateRows: "44px 1fr 56px",
        overflow: "hidden",
      }}
    >
      {/* Chrome */}
      <div style={{ borderBottom: `1px solid ${t.border}`, background: t.panel, display: "flex" }}>
        <div
          style={{
            padding: "0 16px",
            borderRight: `1px solid ${t.border}`,
            display: "flex",
            alignItems: "center",
            minWidth: 220,
          }}
        >
          <BrandMark variantLabel={variantLabel} />
        </div>
        <div style={{ flex: 1, display: "flex", alignItems: "center", padding: "0 16px", gap: 14 }}>
          <Eyebrow>STATUS</Eyebrow>
          <span className="ce-mono" style={{ fontSize: 12, color: t.purged, letterSpacing: "0.04em" }}>
            ▲ NO API KEYS CONFIGURED — EVOLUTION LOCKED
          </span>
        </div>
        <div
          style={{
            padding: "0 16px",
            borderLeft: `1px solid ${t.border}`,
            display: "flex",
            alignItems: "center",
            gap: 10,
          }}
        >
          <Eyebrow>STORAGE</Eyebrow>
          <span className="ce-mono" style={{ fontSize: 11 }}>
            LOCAL BROWSER
          </span>
        </div>
      </div>

      {/* Body */}
      <div
        style={{
          padding: 24,
          overflow: "auto",
          display: "grid",
          gridTemplateRows: "auto 1fr",
          gap: 18,
          minHeight: 0,
        }}
      >
        {/* Intro */}
        <div
          style={{
            border: `1px solid ${t.border}`,
            background: t.panel,
            padding: "18px 22px",
            display: "grid",
            gridTemplateColumns: "1.4fr 1fr",
            gap: 24,
            alignItems: "center",
          }}
        >
          <div>
            <div className="ce-mono" style={{ fontSize: 10, letterSpacing: "0.2em", color: t.muted }}>
              §01 · INITIAL CONFIGURATION
            </div>
            <h1 style={{ margin: "6px 0 4px", fontSize: 30, fontWeight: 700, letterSpacing: "-0.01em", lineHeight: 1.05 }}>
              Bring your own key.
            </h1>
            <p style={{ margin: 0, fontSize: 14, color: t.muted, lineHeight: 1.5, maxWidth: 540 }}>
              ChatEvolve has no backend. Variants are generated by calling the provider you configure
              directly from your browser. Add a key for at least one provider to begin evolution —
              switch providers and models per session afterward.
            </p>
          </div>
          <div style={{ display: "grid", gridTemplateColumns: "1fr", border: `1px solid ${t.border}` }}>
            {RULES.map((rule, i) => (
              <div
                key={i}
                style={{
                  padding: "8px 12px",
                  borderBottom: i < RULES.length - 1 ? `1px solid ${t.hairline}` : "none",
                  display: "flex",
                  gap: 10,
                }}
              >
                <span className="ce-mono ce-tick" style={{ fontSize: 11, color: t.muted, minWidth: 14 }}>
                  {String(i + 1).padStart(2, "0")}
                </span>
                <span style={{ fontSize: 12.5, color: t.ink }}>{rule}</span>
              </div>
            ))}
          </div>
        </div>

        <ProviderGrid
          keys={keys}
          preferredModels={preferredModels}
          onSetKey={onSetKey}
          onSetModel={onSetModel}
          {...(onVerify ? { onVerify } : {})}
          compact
        />
      </div>

      {/* Bottom bar */}
      <div
        style={{
          borderTop: `1px solid ${t.border}`,
          background: t.panel,
          display: "grid",
          gridTemplateColumns: "1fr 280px",
        }}
      >
        <div style={{ display: "flex", alignItems: "center", padding: "0 22px", gap: 16 }}>
          <Eyebrow>CONFIGURED</Eyebrow>
          <div style={{ display: "flex", gap: 6 }}>
            {PROVIDER_ORDER.map((pid) => {
              const ok = !!keys[pid];
              return (
                <span
                  key={pid}
                  className="ce-mono"
                  style={{
                    fontSize: 10,
                    letterSpacing: "0.14em",
                    padding: "4px 8px",
                    border: `1px solid ${t.border}`,
                    background: ok ? t.dominantFill : "transparent",
                    color: t.ink,
                    opacity: ok ? 1 : 0.55,
                  }}
                >
                  {ok ? "◼" : "◻"} {PROVIDERS[pid].name.toUpperCase()}
                </span>
              );
            })}
          </div>
          <span className="ce-mono" style={{ fontSize: 11, color: t.muted, marginLeft: "auto", letterSpacing: "0.04em" }}>
            {configured.length} / 4 PROVIDERS · ADD ANY ONE TO BEGIN
          </span>
        </div>
        <button
          type="button"
          disabled={!hasAnyKey}
          onClick={onBegin}
          style={{
            background: hasAnyKey ? t.ink : "transparent",
            color: hasAnyKey ? t.paper : t.muted,
            border: "none",
            borderLeft: `1px solid ${t.border}`,
            cursor: hasAnyKey ? "pointer" : "not-allowed",
            fontFamily: "'IBM Plex Mono', ui-monospace, monospace",
            fontSize: 14,
            letterSpacing: "0.18em",
            fontWeight: 600,
            display: "flex",
            flexDirection: "column",
            alignItems: "flex-start",
            justifyContent: "center",
            padding: "0 22px",
            gap: 2,
          }}
        >
          {hasAnyKey ? "BEGIN EVOLUTION →" : "LOCKED"}
          <span style={{ fontSize: 9.5, letterSpacing: "0.18em", opacity: 0.7, fontWeight: 400 }}>{sessionLabel}</span>
        </button>
      </div>
    </div>
  );
}
